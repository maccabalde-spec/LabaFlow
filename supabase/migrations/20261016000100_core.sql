create or replace function public.award_points(recipient_id uuid, amount integer)
returns integer
language plpgsql security definer
set search_path = ''
as $$
declare next_points integer;
begin
  if auth.role() <> 'service_role' and not (select public.is_laundry_staff()) then
    raise exception 'staff access required';
  end if;
  if amount <= 0 or amount > 100000 then
    raise exception 'amount must be between 1 and 100000';
  end if;
  update public.profiles set points = points + amount, updated_at = now()
  where id = recipient_id returning points into next_points;
  if next_points is null then raise exception 'customer profile not found'; end if;
  return next_points;
end;
$$;
revoke all on function public.award_points(uuid, integer) from public, anon;
grant execute on function public.award_points(uuid, integer) to authenticated, service_role;
