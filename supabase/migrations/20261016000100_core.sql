create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  public_id bigint generated by default as identity unique,
  full_name text not null default '',
  email text not null default '',
  phone text not null default '',
  role text not null default 'CUSTOMER'
    check (role in ('ADMIN', 'SELLER', 'CUSTOMER')),
  points integer not null default 0 check (points >= 0),
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- The project already has profiles with a user_role enum. Add app columns
-- without replacing existing account data, and store enum values in lowercase.
alter table public.profiles add column if not exists public_id bigint generated by default as identity;
alter table public.profiles add column if not exists email text not null default '';
alter table public.profiles add column if not exists points integer not null default 0;
alter table public.profiles add column if not exists avatar_url text;
create unique index if not exists profiles_public_id_uidx on public.profiles (public_id);

create or replace function public.is_laundry_staff()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role::text in ('admin', 'seller')
  );
$$;

create or replace function public.create_profile_for_auth_user()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, email, phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1), ''),
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'phone', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.sync_profile_email()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
begin
  if new.email is distinct from old.email then
    update public.profiles set email = coalesce(new.email, ''), updated_at = now()
    where id = new.id;
  end if;
  return new;
end;
$$;

create or replace function public.protect_profile_privileges()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if coalesce(auth.role(), '') <> 'service_role' and
     (new.role is distinct from old.role or
      new.points is distinct from old.points or
      new.public_id is distinct from old.public_id) then
    raise exception 'role, points, and public_id are managed by the server';
  end if;
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute procedure public.create_profile_for_auth_user();

drop trigger if exists on_auth_user_email_updated on auth.users;
create trigger on_auth_user_email_updated
  after update of email on auth.users
  for each row execute procedure public.sync_profile_email();

drop trigger if exists protect_profile_privileges on public.profiles;
create trigger protect_profile_privileges
  before update on public.profiles
  for each row execute procedure public.protect_profile_privileges();

alter table public.profiles enable row level security;
revoke all on public.profiles from anon, authenticated;
grant select, update on public.profiles to authenticated;
drop policy if exists "profile owner or staff can read profiles" on public.profiles;
create policy "profile owner or staff can read profiles"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or (select public.is_laundry_staff()));
drop policy if exists "profile owner can update public fields" on public.profiles;
create policy "profile owner can update public fields"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

